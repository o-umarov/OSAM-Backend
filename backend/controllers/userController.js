import userModel from "../models/userModel.js"
import validator from "validator"
import bcrypt from "bcrypt"
import jwt from "jsonwebtoken"

const createToken = (id)=>{
    return jwt.sign({id}, process.env.JWT_SECRET)
}
// Router for user Login
const loginUser = async (req, res) =>{
try {
    const {email, password} = req.body;
    const user = await userModel.findOne({email});
    if(!user){
        return res.json({success: false, message: "User doesn't exist"})
    }
    const isMatch = await bcrypt.compare(password, user.password);
    if(isMatch){
       const token = createToken(user._id)
       res.json({success: true, token})  
    } else {
        res.json({success: false, message: "Invalid credentials"})
    }
} catch (error) {
     console.log("Error: ", error)
    res.json({success: false, message: error.message})
}
}

// Router for user Register
const registerUser = async (req, res) =>{
try {
    const {name, email, password} = req.body
    // User Existence Check
    const exists = await userModel.findOne({email});
    if(exists){
        return res.json({success: false, message: "User alsready exists"})
    }
    //Email and password validation Check
    if (!validator.isEmail(email)) {
        return res.json({success: false, message: "Please enter a valid email"})
    }
    if (password.length < 8) {
        return res.json({success: false, message: "Please enter a strong password"})
    }
    //Password Hashing
    const salt = await bcrypt.genSalt(10)
    const hashedPassword = await bcrypt.hash(password, salt)
    // User Creating Logic
    const newUser = new userModel({
        name,
        email,
        password:hashedPassword
    }) 
    const user = await newUser.save() // in DB => _id is generated by default
    const token =  createToken(user._id)
    res.json({success: true, user} )
    } catch (error) {
    console.log("Error: ", error)
    res.json({success: false, message: error.message})
}
}
// Router for admin Login
const adminLogin = async (req, res) =>{
    try {
        const {email, password} = req.body
        if (email === process.env.ADMIN_EMAIL && password === process.env.ADMIN_PASSWORD) {
            const token = jwt.sign(email+password, process.env.JWT_SECRET);
            res.json({success: true, token})
        } else{
            res.json({success: false, message: "Login or password is invalid"})
        }
    } catch (error) {
        console.log("Error: ", error)
    res.json({success: false, message: error.message})
    }
}

export {loginUser, registerUser, adminLogin}